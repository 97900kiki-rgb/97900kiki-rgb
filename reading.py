def _euro(word):
    """받침에 따라 '로' 인지 '으로' 인지 고른다.

    "30대 초반로" 처럼 어색해지는 것을 막는다. 한글 종성 인덱스가 0(받침 없음)
    이거나 8(ㄹ)이면 '로', 그밖에는 '으로'.
    """
    if not word:
        return "로"
    ch = word[-1]
    if not ("가" <= ch <= "힣"):
        return "로"
    return "로" if (ord(ch) - 0xAC00) % 28 in (0, 8) else "으로"


def past_note(brief, hist):
    """다시 오신 분께 쓸 프롬프트 조각. 처음 오신 분이면 빈 글.

    지난 감정서를 통째로 넣지 않고 **앞부분만** 넣는다. 길게 넣으면 새 감정서가
    지난 것을 베끼고, 짧게 넣으면 흐름만 잇는다. 우리가 바라는 것은 뒤쪽이다.
    """
    if not brief or not hist:
        return ""
    days = brief.get("days_since_last")
    lines = []
    for v in hist[:3]:
        d = (v.get("ts") or "")[:10]
        s = (v.get("summary") or "").strip().replace("\n", " ")[:260]
        bit = "- %s" % d
        if v.get("mood"):
            bit += " (그날 기분: %s)" % v["mood"]
        if v.get("condition"):
            bit += " (몸: %s)" % v["condition"]
        if s:
            bit += "\n  그때 본 것: %s…" % s
        lines.append(bit)
    return """

[다시 찾아온 분이오 — 이 대목을 감정서 첫머리에 자연스럽게 녹이시오]
- 이름 {name}, 이번이 {n}번째 걸음이며 지난 걸음으로부터 {days}일이 지났소.
- 첫머리에서 반갑게 맞이하고, **관상은 큰 틀에서 바뀌지 않으나 결은 달라질 수 있다**는
  뜻을 한두 문장으로 짚으시오.
- 아래는 지난 걸음의 기록이오. 그때와 견주어 **달라진 결**을 한 대목이라도 짚어 주시오.
  다만 지난 글을 옮겨 적지는 마시오.
{lines}
- 기분이나 몸 상태를 적어 두셨다면 안부를 묻듯 스치듯 언급하시오. **다만 병이나
  치료를 말하지 말고, 진단하지 마시오.** 아솔은 의원이 아니라 관상가요.
""".format(name=brief.get("name", ""), n=(brief.get("visits") or 0) + 1,
           days=days if days is not None else "얼마",
           lines="\n".join(lines))


